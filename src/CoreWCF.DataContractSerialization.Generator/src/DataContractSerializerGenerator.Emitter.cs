            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
            _builder.AppendLine();
            _builder.AppendLine($"{indentor}name = __value.Substring(__colon + 1);");
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
        }

        /// <summary>
        /// Emits the reader for an <c>XmlQualifiedName</c> value.
        /// </summary>
        /// <remarks>
        /// Mirrors XmlReaderDelegator.ReadElementContentAsQName, and the shape matters: the prefix
        /// is declared on the element the writer opened, so it has to be resolved before that
        /// element's end tag is consumed and its scope popped. Reading the text and the end tag in
        /// one call - ReadElementContentAsString - would leave nothing to resolve against.
        /// </remarks>
        private void EmitQNameReadHelper(Indentor indentor)
        {
            _builder.AppendLine();
            _builder.AppendLine($"{indentor}private static global::System.Xml.XmlQualifiedName ReadQName({DictionaryReader} reader)");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            // The writer emits nothing at all for the empty name, so an empty element is how it
            // comes back - not an empty string that happens to parse to the same thing.
            _builder.AppendLine($"{indentor}if (reader.IsEmptyElement)");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            _builder.AppendLine($"{indentor}reader.Read();");
            _builder.AppendLine($"{indentor}return global::System.Xml.XmlQualifiedName.Empty;");
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
            _builder.AppendLine();
            _builder.AppendLine($"{indentor}reader.ReadStartElement();");
            _builder.AppendLine($"{indentor}string __text = reader.ReadContentAsString();");
            _builder.AppendLine($"{indentor}global::System.Xml.XmlQualifiedName __name;");
            _builder.AppendLine();
            _builder.AppendLine($"{indentor}if (__text.Length == 0)");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            _builder.AppendLine($"{indentor}__name = global::System.Xml.XmlQualifiedName.Empty;");
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
            _builder.AppendLine($"{indentor}else");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            _builder.AppendLine($"{indentor}int __colon = __text.IndexOf(':');");
            _builder.AppendLine($"{indentor}string __prefix = __colon < 0 ? string.Empty : __text.Substring(0, __colon);");
            _builder.AppendLine($"{indentor}string __namespace = reader.LookupNamespace(__prefix);");
            _builder.AppendLine();
            _builder.AppendLine($"{indentor}if (__namespace == null)");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            _builder.AppendLine($"{indentor}throw new global::System.Runtime.Serialization.SerializationException(");
            indentor.Increment();
            _builder.AppendLine($"{indentor}\"Invalid qualified name '\" + __text + \"': the prefix is not declared.\");");
            indentor.Decrement();
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
            _builder.AppendLine();
            _builder.AppendLine($"{indentor}__name = new global::System.Xml.XmlQualifiedName(__text.Substring(__colon + 1), __namespace);");
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
            _builder.AppendLine();
            _builder.AppendLine($"{indentor}reader.ReadEndElement();");
            _builder.AppendLine($"{indentor}return __name;");
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
        }

        /// <summary>
        /// Emits the writer for an <c>XmlQualifiedName</c> value.
        /// </summary>
        /// <remarks>
        /// Mirrors XmlWriterDelegator.WriteQName. The empty name writes nothing at all - not an
        /// empty string - and otherwise the value's namespace is declared before the qualified name
        /// is written, so the writer has a prefix to render it with.
        /// </remarks>
        private void EmitQNameHelper(Indentor indentor)
        {
            _builder.AppendLine();
            _builder.AppendLine($"{indentor}private static void WriteQName({DictionaryWriter} writer, global::System.Xml.XmlQualifiedName value)");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            _builder.AppendLine($"{indentor}if (value != global::System.Xml.XmlQualifiedName.Empty)");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            _builder.AppendLine($"{indentor}writer.WriteXmlnsAttribute(null, value.Namespace);");
            _builder.AppendLine($"{indentor}writer.WriteQualifiedName(value.Name, value.Namespace);");
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
        }

        /// <summary>
        /// Emits the writer for one item of an <c>object[]</c>, whose element is already open.
        /// </summary>
        /// <remarks>
        /// Deliberately narrower than a member's boxed switch: it covers the primitives, a bare
        /// object and null, and throws for anything else. A contract or enum inside an untyped array
        /// would need the containing contract's known types, which an item writer shared across the
        /// whole context does not have.
        /// </remarks>
        private void EmitAnyTypeHelper(Indentor indentor)
        {
            _builder.AppendLine();
            _builder.AppendLine($"{indentor}private static void WriteAnyType({DictionaryWriter} writer, object value)");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            _builder.AppendLine($"{indentor}if (value == null)");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            _builder.AppendLine($"{indentor}WriteNil(writer);");
            _builder.AppendLine($"{indentor}return;");
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
            _builder.AppendLine();
            _builder.AppendLine($"{indentor}global::System.Type __runtimeType = value.GetType();");
            _builder.AppendLine($"{indentor}if (__runtimeType == typeof(object))");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            _builder.AppendLine($"{indentor}// anyType: neither i:type nor content");
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");

            foreach ((string clrType, MemberKind kind, string xsiName, string xsiNamespace, bool _) in BoxedPrimitives)
            {
                _builder.AppendLine($"{indentor}else if (__runtimeType == typeof({clrType}))");
                _builder.AppendLine($"{indentor}{{");
                indentor.Increment();
                EmitXsiType(indentor, xsiName, xsiNamespace);
                _builder.AppendLine($"{indentor}{WriteValueStatement(kind, $"(({clrType})value)")}");
                indentor.Decrement();
                _builder.AppendLine($"{indentor}}}");
            }

            _builder.AppendLine($"{indentor}else");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            _builder.AppendLine($"{indentor}throw new global::System.Runtime.Serialization.SerializationException(");
            indentor.Increment();
            _builder.AppendLine($"{indentor}\"Type '\" + __runtimeType.FullName + \"' cannot be written as an untyped array item.\");");
            indentor.Decrement();
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
        }

        /// <summary>
        /// Emits the <c>DateOnly</c> and <c>TimeOnly</c> writers, and the runtime test they depend on.
        /// </summary>
        /// <remarks>
        /// <para>
        /// These two are the only members whose wire format is decided by the runtime rather than
        /// the contract. Up to .NET 9 DataContractSerializer did not recognise them and wrote a
        /// contract with no members - an empty element that drops the value entirely. .NET 10 writes
        /// them as primitives. Verified to be a runtime difference and not a target-framework one:
        /// a net8.0 assembly run on .NET 10 produces the .NET 10 format, so a compile-time decision
        /// would be wrong under roll-forward.
        /// </para>
        /// <para>
        /// The formats are XmlWriterDelegator's: "yyyy-MM-dd" for a date, and "HH:mm:ss.FFFFFFF"
        /// for a time - optional fractional digits, so trailing zeros and the separating dot are
        /// omitted rather than padded.
        /// </para>
        /// </remarks>
        private void EmitDateOnlyHelpers(Indentor indentor)
        {
            _builder.AppendLine();
            _builder.AppendLine($"{indentor}/// <summary>Whether this runtime writes DateOnly and TimeOnly as primitives.</summary>");
            _builder.AppendLine($"{indentor}private static readonly bool {DateOnlyIsPrimitive} =");
            indentor.Increment();
            _builder.AppendLine($"{indentor}global::System.Environment.Version.Major >= 10;");
            indentor.Decrement();
            _builder.AppendLine();
            _builder.AppendLine($"{indentor}private static void WriteDateOnly({DictionaryWriter} writer, global::System.DateOnly value)");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            _builder.AppendLine($"{indentor}if ({DateOnlyIsPrimitive})");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            _builder.AppendLine($"{indentor}writer.WriteString(value.ToString(\"yyyy-MM-dd\", global::System.Globalization.CultureInfo.InvariantCulture));");
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
            _builder.AppendLine();
            _builder.AppendLine($"{indentor}private static void WriteTimeOnly({DictionaryWriter} writer, global::System.TimeOnly value)");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            _builder.AppendLine($"{indentor}if ({DateOnlyIsPrimitive})");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            _builder.AppendLine($"{indentor}writer.WriteString(value.ToString(\"HH:mm:ss.FFFFFFF\", global::System.Globalization.CultureInfo.InvariantCulture));");
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
            _builder.AppendLine();
            _builder.AppendLine($"{indentor}private static global::System.DateOnly ReadDateOnly(string text)");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            // Not a fallback: before .NET 10 the serializer does not know what a DateOnly is and
            // writes a contract with no members, so the recorded element genuinely carries no value.
            // Returning default is what the document says, and it is also what the reflection-based
            // reader produces from the same bytes - which is what keeps the round-trip exact.
            _builder.AppendLine($"{indentor}if (!{DateOnlyIsPrimitive})");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            _builder.AppendLine($"{indentor}return default;");
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
            _builder.AppendLine();
            _builder.AppendLine($"{indentor}return global::System.DateOnly.ParseExact(");
            indentor.Increment();
            _builder.AppendLine($"{indentor}text,");
            _builder.AppendLine($"{indentor}\"yyyy-MM-dd\",");
            _builder.AppendLine($"{indentor}global::System.Globalization.DateTimeFormatInfo.InvariantInfo,");
            _builder.AppendLine($"{indentor}global::System.Globalization.DateTimeStyles.AllowLeadingWhite | global::System.Globalization.DateTimeStyles.AllowTrailingWhite);");
            indentor.Decrement();
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
            _builder.AppendLine();
            _builder.AppendLine($"{indentor}private static global::System.TimeOnly ReadTimeOnly(string text)");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            _builder.AppendLine($"{indentor}if (!{DateOnlyIsPrimitive})");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            _builder.AppendLine($"{indentor}return default;");
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
            _builder.AppendLine();
            // Deliberately not TimeOnly.ParseExact. XmlReaderDelegator.ReadElementContentAsTimeOnly
            // goes through XmlConvert.ToDateTimeOffset, which accepts a Z or an offset that
            // "HH:mm:ss.FFFFFFF" would reject. The ParseTimeOnly helper sitting next to it upstream
            // is never called, and copying it instead would narrow what this reader accepts.
            _builder.AppendLine($"{indentor}return global::System.TimeOnly.FromTimeSpan(");
            indentor.Increment();
            _builder.AppendLine($"{indentor}{XmlConvert}.ToDateTimeOffset(text).TimeOfDay);");
            indentor.Decrement();
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
        }

        /// <summary>
        /// Emits the method that reads a contract's members from an already-open element.
        /// </summary>
        private void EmitContentReader(Indentor indentor, ContractSpec contract)
        {
            _builder.AppendLine($"{indentor}/// <summary>Reads the members of {contract.ContractName} into an existing instance.</summary>");
            _builder.AppendLine($"{indentor}private static void {ContentReaderName(contract)}({DictionaryReader} reader, {(contract.IsValueType ? "ref " : string.Empty)}{contract.FullyQualifiedName} value, {ReadScope} scope)");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            List<(MemberSpec Member, string Namespace)> members = FlattenedMembers(contract);

            _builder.AppendLine($"{indentor}int __matched = -1;");
            _builder.AppendLine($"{indentor}while (reader.NodeType == global::System.Xml.XmlNodeType.Element)");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();

            int index = 0;
            foreach ((MemberSpec member, string memberNamespace) in members)
            {
                string keyword = index == 0 ? "if" : "else if";
                _builder.AppendLine($"{indentor}{keyword} (__matched < {index}");
                indentor.Increment();
                _builder.AppendLine($"{indentor}&& reader.LocalName == {Literal(member.Name)}");
                _builder.AppendLine($"{indentor}&& reader.NamespaceURI == {Literal(memberNamespace)})");
                indentor.Decrement();
                _builder.AppendLine($"{indentor}{{");
                indentor.Increment();
                EmitMemberRead(indentor, member);
                _builder.AppendLine($"{indentor}__matched = {index};");
                indentor.Decrement();
                _builder.AppendLine($"{indentor}}}");
                index++;
            }

            if (members.Count > 0)
            {
                _builder.AppendLine($"{indentor}else");
                _builder.AppendLine($"{indentor}{{");
                indentor.Increment();
            }

            // An element matching no member is skipped, exactly as the reflection reader does with
            // one it cannot place. That is what lets a document carry members this contract does
            // not know about without the read failing.
            _builder.AppendLine($"{indentor}reader.Skip();");

            if (members.Count > 0)
            {
                indentor.Decrement();
                _builder.AppendLine($"{indentor}}}");
            }

            _builder.AppendLine();
            _builder.AppendLine($"{indentor}reader.MoveToContent();");
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
        }

        private void EmitMemberRead(Indentor indentor, MemberSpec member)
        {
            string target = "value." + member.MemberName;

            if (member.Kind == MemberKind.Contract)
            {
                EmitNestedContractRead(indentor, member, target);
                return;
            }

            if (member.Kind == MemberKind.Collection)
            {
                EmitCollectionRead(indentor, member, target);
                return;
            }

            if (member.Kind == MemberKind.Dictionary)
            {
                EmitDictionaryRead(indentor, member, target);
                return;
            }

            if (member.Kind == MemberKind.Object)
            {
                EmitBoxedMemberRead(indentor, member, target);
                return;
            }

            EmitValueRead(indentor, member.Kind, member.NestedContractFullyQualifiedName, target, "__text");
        }

        /// <summary>
        /// Emits the read of a member declared as <c>object</c>, <c>ValueType</c>, <c>Enum</c> or
        /// <c>Array</c>.
        /// </summary>
        /// <remarks>
        /// The inverse of EmitObjectMember, and it has three tables to consult rather than one: the
        /// known contracts, the known enums, and the XSD names of the primitives. What the declared
        /// type buys is a check - a value the member cannot hold is rejected here rather than
        /// surfacing later as an InvalidCastException from generated code.
        /// </remarks>
        private void EmitBoxedMemberRead(Indentor indentor, MemberSpec member, string target)
        {
            string declaredType = member.Boxed switch
            {
                BoxedDeclaration.ValueType => "global::System.ValueType",
                BoxedDeclaration.Enum => "global::System.Enum",
                BoxedDeclaration.Array => "global::System.Array",
                _ => "object"
            };

            _builder.AppendLine($"{indentor}if (IsNil(reader))");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            _builder.AppendLine($"{indentor}reader.Skip();");
            _builder.AppendLine($"{indentor}{target} = default;");
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
            _builder.AppendLine($"{indentor}else");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            _builder.AppendLine($"{indentor}ReadXsiType(reader, out string __typeName, out string __typeNamespace);");
            _builder.AppendLine();

            bool first = true;

            if (member.Boxed == BoxedDeclaration.Array)
            {
                // The only array the writer emits is object[], and it announces no i:type at all -
                // the items carry their own.
                _builder.AppendLine($"{indentor}if (__typeName == null)");
                _builder.AppendLine($"{indentor}{{");
                indentor.Increment();
                EmitUntypedArrayRead(indentor, target);
                indentor.Decrement();
                _builder.AppendLine($"{indentor}}}");
                first = false;
            }

            foreach (string candidate in member.Candidates)
            {
                ContractSpec spec = _contractSpecs[candidate];

                _builder.AppendLine($"{indentor}{(first ? "if" : "else if")} (__typeName == {Literal(spec.ContractName)}");
                indentor.Increment();
                _builder.AppendLine($"{indentor}&& __typeNamespace == {Literal(spec.ContractNamespace)})");
                indentor.Decrement();
                first = false;
                _builder.AppendLine($"{indentor}{{");
                indentor.Increment();
                EmitTypedContractRead(indentor, spec, target);
                indentor.Decrement();
                _builder.AppendLine($"{indentor}}}");
            }

            foreach (string enumCandidate in member.EnumCandidates)
            {
                EnumSpec spec = _enumSpecs[enumCandidate];

                _builder.AppendLine($"{indentor}{(first ? "if" : "else if")} (__typeName == {Literal(spec.ContractName)}");
                indentor.Increment();
                _builder.AppendLine($"{indentor}&& __typeNamespace == {Literal(spec.ContractNamespace)})");
                indentor.Decrement();
                first = false;
                _builder.AppendLine($"{indentor}{{");
                indentor.Increment();
                _builder.AppendLine($"{indentor}string __enumText = reader.ReadElementContentAsString();");
                _builder.AppendLine($"{indentor}{target} = {ReadEnumExpression(enumCandidate, "__enumText")};");
                indentor.Decrement();
                _builder.AppendLine($"{indentor}}}");
            }

            if (member.Boxed is BoxedDeclaration.Enum or BoxedDeclaration.Array)
            {
                // Neither admits a primitive, so an unmatched name is the end of the road rather
                // than a reason to consult the XSD table.
                _builder.AppendLine($"{indentor}{(first ? "if (true)" : "else")}");
                _builder.AppendLine($"{indentor}{{");
                indentor.Increment();
                _builder.AppendLine($"{indentor}throw new global::System.Runtime.Serialization.SerializationException(");
                indentor.Increment();
                _builder.AppendLine($"{indentor}\"Element contains data from a type that maps to the name '\" + __typeNamespace + \":\" + __typeName +");
                _builder.AppendLine($"{indentor}\"'. The deserializer has no knowledge of any type that maps to this name.\");");
                indentor.Decrement();
                indentor.Decrement();
                _builder.AppendLine($"{indentor}}}");
            }
            else
            {
                _builder.AppendLine($"{indentor}{(first ? "if (true)" : "else")}");
                _builder.AppendLine($"{indentor}{{");
                indentor.Increment();
                _builder.AppendLine($"{indentor}object __boxed = ReadBoxedValue(reader, __typeName, __typeNamespace);");

                if (declaredType != "object")
                {
                    _builder.AppendLine();
                    _builder.AppendLine($"{indentor}if (!(__boxed is {declaredType}))");
                    _builder.AppendLine($"{indentor}{{");
                    indentor.Increment();
                    _builder.AppendLine($"{indentor}throw new global::System.Runtime.Serialization.SerializationException(");
                    indentor.Increment();
                    _builder.AppendLine($"{indentor}\"Element contains data from a type that maps to the name '\" + __typeNamespace + \":\" + __typeName +");
                    _builder.AppendLine($"{indentor}\"', which this member cannot hold.\");");
                    indentor.Decrement();
                    indentor.Decrement();
                    _builder.AppendLine($"{indentor}}}");
                    _builder.AppendLine();
                }

                _builder.AppendLine($"{indentor}{target} = ({declaredType})__boxed;");
                indentor.Decrement();
                _builder.AppendLine($"{indentor}}}");
            }

            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
        }

        /// <summary>Emits the read of an <c>object[]</c>, whose items each announce their own type.</summary>
        private void EmitUntypedArrayRead(Indentor indentor, string target) =>
            EmitSequenceRead(
                indentor,
                ContainerTypeOf("object", isArrayList: false),
                "__items",
                FinishOf(isArray: true),
                target,
                (inner, container) => _builder.AppendLine($"{inner}{container}.Add(ReadAnyType(reader));"));

        /// <summary>
        /// Emits the read of one element whose content is a value, into an lvalue that already
        /// exists.
        /// </summary>
        /// <remarks>
        /// <para>
        /// Serves a member, a collection item and half a dictionary entry alike, because on the wire
        /// they are the same thing: an element carrying one value, which may instead carry i:nil.
        /// </para>
        /// <para>
        /// The nil branch assigns <c>default</c> in a statement rather than through a conditional
        /// expression, and that is not a style choice. In <c>x = c ? default : e</c> the conditional
        /// takes its type from <c>e</c>, so a nil <c>int?</c> would come back as 0 rather than null.
        /// Assigning to the target directly lets the target's own type decide.
        /// </para>
        /// </remarks>
        private void EmitValueRead(Indentor indentor, MemberKind kind, string? enumFullyQualifiedName, string target, string textName)
        {
            if (ElementValueExpression(kind) is string element)
            {
                _builder.AppendLine($"{indentor}if (IsNil(reader))");
                _builder.AppendLine($"{indentor}{{");
                indentor.Increment();
                _builder.AppendLine($"{indentor}reader.Skip();");
                _builder.AppendLine($"{indentor}{target} = default;");
                indentor.Decrement();
                _builder.AppendLine($"{indentor}}}");
                _builder.AppendLine($"{indentor}else");
                _builder.AppendLine($"{indentor}{{");
                indentor.Increment();
                _builder.AppendLine($"{indentor}{target} = {element};");
                indentor.Decrement();
                _builder.AppendLine($"{indentor}}}");
                return;
            }

            string readValue = kind == MemberKind.Enum
                ? ReadEnumExpression(enumFullyQualifiedName, textName)!
                : ReadValueExpression(kind, textName)!;

            _builder.AppendLine($"{indentor}string {textName} = ReadText(reader);");
            _builder.AppendLine($"{indentor}if ({textName} == null)");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            _builder.AppendLine($"{indentor}{target} = default;");
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
            _builder.AppendLine($"{indentor}else");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            _builder.AppendLine($"{indentor}{target} = {readValue};");
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
        }

        /// <summary>
        /// For the kinds read from the element rather than from its text, the expression that reads
        /// one - or null for the kinds that go through <see cref="ReadValueExpression"/>.
        /// </summary>
        /// <remarks>
        /// Three kinds are not text at all. A byte array is base64 the reader decodes itself, a
        /// DateTimeOffset is a two-member contract rather than a value, and a QName has to resolve a
        /// prefix against the element still on the reader.
        /// </remarks>
        private static string? ElementValueExpression(MemberKind kind) => kind switch
        {
            MemberKind.ByteArray => "reader.ReadElementContentAsBase64()",
            MemberKind.DateTimeOffset => "ReadDateTimeOffset(reader)",
            MemberKind.QName => "ReadQName(reader)",

            // An untyped item announces its own type and its own i:nil, so it consumes the whole
            // element the way the other three do.
            MemberKind.Object => "ReadAnyType(reader)",
            _ => null
        };

        /// <summary>
        /// Emits the read of a member that is itself a contract, written inline by the writer.
        /// </summary>
        /// <remarks>
        /// The wire format has no second wrapping element, so the member element <em>is</em> the
        /// nested contract's element: open it, hand the reader to that contract's content reader,
        /// close it. The mirror of what the content writer does.
        /// </remarks>
        private void EmitNestedContractRead(Indentor indentor, MemberSpec member, string target)
        {
            ContractSpec nested = _contractSpecs[member.NestedContractFullyQualifiedName!];

            _builder.AppendLine($"{indentor}if (IsNil(reader))");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            _builder.AppendLine($"{indentor}reader.Skip();");
            _builder.AppendLine($"{indentor}{target} = default;");
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
            _builder.AppendLine($"{indentor}else");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();

            if (member.Candidates.Count > 0)
            {
                EmitDispatchedRead(indentor, nested, member.Candidates, target);
            }
            else
            {
                EmitTypedContractRead(indentor, nested, target);
            }

            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
        }

        /// <summary>
        /// Emits the read of one contract into a target, from an element that is open but not
        /// entered.
        /// </summary>
        /// <remarks>
        /// The wire format has no second wrapping element, so the element the reader is sitting on
        /// <em>is</em> this contract's element: open it, hand the reader to its content reader,
        /// close it. The mirror of what the content writer does.
        /// </remarks>
        private void EmitTypedContractRead(Indentor indentor, ContractSpec contract, string target)
        {
            if (!contract.IsReference)
            {
                EmitConstructAndRead(indentor, contract, target);
                return;
            }

            // A z:Ref carries nothing but the attribute, so the element is skipped whole. It can
            // only point backwards - the writer assigns an id the first time it writes an instance -
            // so an id that is not in the table is a malformed document rather than one to revisit.
            _builder.AppendLine($"{indentor}string __ref = reader.GetAttribute(\"Ref\", {Literal(SerializationNamespace)});");
            _builder.AppendLine($"{indentor}if (__ref != null)");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            _builder.AppendLine($"{indentor}reader.Skip();");
            _builder.AppendLine($"{indentor}{target} = ({contract.FullyQualifiedName})scope.Get(__ref);");
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
            _builder.AppendLine($"{indentor}else");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            EmitConstructAndRead(indentor, contract, target);
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
        }

        private void EmitConstructAndRead(Indentor indentor, ContractSpec contract, string target)
        {
            string typeName = contract.FullyQualifiedName;

            _builder.AppendLine($"{indentor}{typeName} __typed = new {typeName}();");

            if (contract.IsReference)
            {
                _builder.AppendLine($"{indentor}scope.Add(reader.GetAttribute(\"Id\", {Literal(SerializationNamespace)}), __typed);");
            }

            _builder.AppendLine($"{indentor}if (reader.IsEmptyElement)");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            _builder.AppendLine($"{indentor}reader.Read();");
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
            _builder.AppendLine($"{indentor}else");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            _builder.AppendLine($"{indentor}reader.ReadStartElement();");
            _builder.AppendLine($"{indentor}reader.MoveToContent();");
            _builder.AppendLine($"{indentor}{ContentReaderName(contract)}(reader, {(contract.IsValueType ? "ref " : string.Empty)}__typed, scope);");
            _builder.AppendLine($"{indentor}reader.ReadEndElement();");
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
            _builder.AppendLine();
            _builder.AppendLine($"{indentor}{target} = __typed;");
        }

        /// <summary>
        /// Emits the read of a value whose runtime contract is announced by <c>i:type</c>.
        /// </summary>
        /// <remarks>
        /// <para>
        /// The inverse of EmitPolymorphicMember, and it has to resolve a name rather than announce
        /// one. Mirrors XmlObjectSerializerReadContext: the i:type is resolved against the known
        /// types, its absence means the declared contract, and a name that resolves to nothing
        /// throws DcTypeNotFoundOnDeserialize rather than falling back to the declared type. Falling
        /// back would produce an instance missing every member the derived contract adds and report
        /// success, which is the failure this whole project exists to prevent.
        /// </para>
        /// <para>
        /// The candidate set is the compile-time known-types closure, so the resolution the
        /// serializer does through reflection is a chain of string comparisons here.
        /// </para>
        /// </remarks>
        private void EmitDispatchedRead(Indentor indentor, ContractSpec declared, EquatableArray<string> candidates, string target)
        {
            _builder.AppendLine($"{indentor}ReadXsiType(reader, out string __typeName, out string __typeNamespace);");
            _builder.AppendLine();

            // The declared contract is both the no-i:type case and a candidate in its own right,
            // since the writer omits i:type for it but a document from elsewhere may still name it.
            _builder.AppendLine($"{indentor}if (__typeName == null");
            indentor.Increment();
            _builder.AppendLine($"{indentor}|| (__typeName == {Literal(declared.ContractName)}");
            indentor.Increment();
            _builder.AppendLine($"{indentor}&& __typeNamespace == {Literal(declared.ContractNamespace)}))");
            indentor.Decrement();
            indentor.Decrement();
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            EmitTypedContractRead(indentor, declared, target);
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");

            foreach (string candidate in candidates)
            {
                ContractSpec spec = _contractSpecs[candidate];

                if (string.Equals(candidate, declared.FullyQualifiedName, StringComparison.Ordinal))
                {
                    continue;
                }

                _builder.AppendLine($"{indentor}else if (__typeName == {Literal(spec.ContractName)}");
                indentor.Increment();
                _builder.AppendLine($"{indentor}&& __typeNamespace == {Literal(spec.ContractNamespace)})");
                indentor.Decrement();
                _builder.AppendLine($"{indentor}{{");
                indentor.Increment();
                EmitTypedContractRead(indentor, spec, target);
                indentor.Decrement();
                _builder.AppendLine($"{indentor}}}");
            }

            _builder.AppendLine($"{indentor}else");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            _builder.AppendLine($"{indentor}throw new global::System.Runtime.Serialization.SerializationException(");
            indentor.Increment();
            _builder.AppendLine($"{indentor}\"Element contains data from a type that maps to the name '\" + __typeNamespace + \":\" + __typeName +");
            _builder.AppendLine($"{indentor}\"'. The deserializer has no knowledge of any type that maps to this name.\");");
            indentor.Decrement();
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
        }

        /// <summary>Whether a contract is announced as something else by some document it may see.</summary>
        private EquatableArray<string> DerivedCandidates(ContractSpec contract)
        {
            List<string> derived = new List<string>();

            foreach (string knownType in contract.KnownTypes)
            {
                if (!_contractSpecs.TryGetValue(knownType, out ContractSpec candidate) || !candidate.IsSupported)
                {
                    continue;
                }

                ContractSpec current = candidate;
                while (current.BaseContractFullyQualifiedName is string baseName)
                {
                    if (string.Equals(baseName, contract.FullyQualifiedName, StringComparison.Ordinal))
                    {
                        derived.Add(knownType);
                        break;
                    }

                    if (!_contractSpecs.TryGetValue(baseName, out ContractSpec baseSpec))
                    {
                        break;
                    }

                    current = baseSpec;
                }
            }

            return new EquatableArray<string>(derived.ToArray());
        }

        /// <summary>
        /// Emits the read of a collection member, accumulating into a list before assigning.
        /// </summary>
        /// <remarks>
        /// An empty collection and a null one are different documents and stay different here: an
        /// empty element yields an empty collection, and only i:nil yields null. Getting that
        /// backwards is invisible until something round-trips.
        /// </remarks>
        private void EmitCollectionRead(Indentor indentor, MemberSpec member, string target)
        {
            _builder.AppendLine($"{indentor}if (IsNil(reader))");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            _builder.AppendLine($"{indentor}reader.Skip();");
            _builder.AppendLine($"{indentor}{target} = default;");
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
            _builder.AppendLine($"{indentor}else");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();

            EmitSequenceRead(
                indentor,
                ContainerTypeOf(member.ElementClrType!, member.CollectionIsArrayList),
                "__items",
                FinishOf(member.CollectionIsArray),
                target,
                (inner, container) =>
                {
                    _builder.AppendLine($"{inner}{member.ElementClrType} __item = default;");

                    if (member.ElementKind == MemberKind.Collection)
                    {
                        EmitJaggedItemRead(inner, member, "__item");
                    }
                    else
                    {
                        EmitValueRead(inner, member.ElementKind, member.ElementEnumFullyQualifiedName, "__item", "__itemText");
                    }

                    _builder.AppendLine($"{inner}{container}.Add(__item);");
                });

            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
        }

        /// <summary>
        /// Emits the read of one item of a jagged collection, which is a collection in its own right.
        /// </summary>
        /// <remarks>
        /// The ArrayOf element is the inner collection's element - there is no second wrapper - so
        /// this is the same loop one level down, over the innermost items. A null inner collection
        /// is i:nil like any other missing reference, which is what the writer records for one.
        /// </remarks>
        private void EmitJaggedItemRead(Indentor indentor, MemberSpec member, string target)
        {
            _builder.AppendLine($"{indentor}if (IsNil(reader))");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            _builder.AppendLine($"{indentor}reader.Skip();");
            _builder.AppendLine($"{indentor}{target} = default;");
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
            _builder.AppendLine($"{indentor}else");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();

            EmitSequenceRead(
                indentor,
                ContainerTypeOf(member.NestedElementClrType!, isArrayList: false),
                "__inner",
                FinishOf(member.NestedCollectionIsArray),
                target,
                (deepest, container) =>
                {
                    _builder.AppendLine($"{deepest}{member.NestedElementClrType} __innerItem = default;");
                    EmitValueRead(deepest, member.NestedElementKind, null, "__innerItem", "__innerText");
                    _builder.AppendLine($"{deepest}{container}.Add(__innerItem);");
                });

            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
        }

        /// <summary>
        /// Emits the loop that fills a container from the children of an element, then assigns it.
        /// </summary>
        /// <remarks>
        /// Serves every sequence on the read side - a typed collection, an untyped object[], and
        /// each half of a jagged one - because they differ only in what a container is and how an
        /// item is read. An empty element yields an empty container and only i:nil yields null,
        /// which is the caller's business rather than this loop's.
        /// </remarks>
        private void EmitSequenceRead(
            Indentor indentor,
            string containerType,
            string container,
            string finish,
            string target,
            Action<Indentor, string> emitItem)
        {
            _builder.AppendLine($"{indentor}{containerType} {container} = new {containerType}();");
            _builder.AppendLine($"{indentor}if (reader.IsEmptyElement)");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            _builder.AppendLine($"{indentor}reader.Read();");
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
            _builder.AppendLine($"{indentor}else");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            _builder.AppendLine($"{indentor}reader.ReadStartElement();");
            _builder.AppendLine($"{indentor}reader.MoveToContent();");
            _builder.AppendLine($"{indentor}while (reader.NodeType == global::System.Xml.XmlNodeType.Element)");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            emitItem(indentor, container);
            _builder.AppendLine($"{indentor}reader.MoveToContent();");
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
            _builder.AppendLine();
            _builder.AppendLine($"{indentor}reader.ReadEndElement();");
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
            _builder.AppendLine();
            _builder.AppendLine($"{indentor}{target} = {container}{finish};");
        }

        private static string ContainerTypeOf(string elementType, bool isArrayList) =>
            isArrayList
                ? "global::System.Collections.ArrayList"
                : $"global::System.Collections.Generic.List<{elementType}>";

        private static string FinishOf(bool isArray) => isArray ? ".ToArray()" : string.Empty;

        /// <summary>
        /// Emits the read of a dictionary member: one pair per entry element.
        /// </summary>
        /// <remarks>
        /// The mirror of EmitDictionaryMember. The entry name and both part names come from the
        /// spec rather than from here, so a name the writer proved against a fixture is the one the
        /// reader looks for. Like every other collection, an empty element yields an empty
        /// dictionary and only i:nil yields null.
        /// </remarks>
        private void EmitDictionaryRead(Indentor indentor, MemberSpec member, string target)
        {
            string keyType = member.KeyClrType!;
            string valueType = member.ValueClrType!;
            string dictionaryType = $"global::System.Collections.Generic.Dictionary<{keyType}, {valueType}>";
            string entryNamespace = member.ItemNamespace!;

            _builder.AppendLine($"{indentor}if (IsNil(reader))");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            _builder.AppendLine($"{indentor}reader.Skip();");
            _builder.AppendLine($"{indentor}{target} = default;");
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
            _builder.AppendLine($"{indentor}else");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            _builder.AppendLine($"{indentor}{dictionaryType} __pairs = new {dictionaryType}();");
            _builder.AppendLine($"{indentor}if (reader.IsEmptyElement)");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            _builder.AppendLine($"{indentor}reader.Read();");
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
            _builder.AppendLine($"{indentor}else");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            _builder.AppendLine($"{indentor}reader.ReadStartElement();");
            _builder.AppendLine($"{indentor}reader.MoveToContent();");
            _builder.AppendLine($"{indentor}while (reader.NodeType == global::System.Xml.XmlNodeType.Element)");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            _builder.AppendLine($"{indentor}{keyType} __key = default;");
            _builder.AppendLine($"{indentor}{valueType} __value = default;");
            _builder.AppendLine();
            _builder.AppendLine($"{indentor}if (reader.IsEmptyElement)");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            _builder.AppendLine($"{indentor}reader.Read();");
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
            _builder.AppendLine($"{indentor}else");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            _builder.AppendLine($"{indentor}reader.ReadStartElement();");
            _builder.AppendLine($"{indentor}reader.MoveToContent();");
            // An entry is an ordinary two-member contract on the wire, so it is matched the way
            // every other one is: forward only, each part at most once.
            _builder.AppendLine($"{indentor}int __part = -1;");
            _builder.AppendLine($"{indentor}while (reader.NodeType == global::System.Xml.XmlNodeType.Element)");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();

            EmitDictionaryPartRead(indentor, "if", 0, "Key", entryNamespace, member.KeyKind, "__key", "__keyText");
            EmitDictionaryPartRead(indentor, "else if", 1, "Value", entryNamespace, member.ValueKind, "__value", "__valueText");

            _builder.AppendLine($"{indentor}else");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            _builder.AppendLine($"{indentor}reader.Skip();");
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
            _builder.AppendLine();
            _builder.AppendLine($"{indentor}reader.MoveToContent();");
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
            _builder.AppendLine();
            _builder.AppendLine($"{indentor}reader.ReadEndElement();");
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
            _builder.AppendLine();
            _builder.AppendLine($"{indentor}__pairs.Add(__key, __value);");
            _builder.AppendLine($"{indentor}reader.MoveToContent();");
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
            _builder.AppendLine();
            _builder.AppendLine($"{indentor}reader.ReadEndElement();");
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
            _builder.AppendLine();
            _builder.AppendLine($"{indentor}{target} = __pairs;");
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
        }

        private void EmitDictionaryPartRead(
            Indentor indentor,
            string keyword,
            int index,
            string name,
            string entryNamespace,
            MemberKind kind,
            string target,
            string textName)
        {
            _builder.AppendLine($"{indentor}{keyword} (__part < {index}");
            indentor.Increment();
            _builder.AppendLine($"{indentor}&& reader.LocalName == {Literal(name)}");
            _builder.AppendLine($"{indentor}&& reader.NamespaceURI == {Literal(entryNamespace)})");
            indentor.Decrement();
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();

            EmitValueRead(indentor, kind, null, target, textName);
            _builder.AppendLine($"{indentor}__part = {index};");
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
        }

        /// <summary>
        /// One contract's members in the order the wire carries them: the base chain flattened
        /// base-first, each member paired with the namespace of the contract that declares it.
        /// </summary>
        /// <remarks>
        /// The writer recurses instead, one call per level, because writing is unconditional. A
        /// reader cannot: it is a single loop over a single monotonically advancing index, and a
        /// per-level loop would let the base's loop swallow the derived members as elements it does
        /// not recognise. Upstream draws the same distinction - ReflectionGetMembers flattens the
        /// chain base-first, and ClassDataContract builds MemberNamespaces by copying the base's
        /// entries before appending its own, which is why an inherited member keeps its declaring
        /// contract's namespace rather than the derived contract's.
        /// </remarks>
        private List<(MemberSpec Member, string Namespace)> FlattenedMembers(ContractSpec contract)
        {
            List<(MemberSpec Member, string Namespace)> flattened = new List<(MemberSpec, string)>();
            Append(contract);
            return flattened;

            void Append(ContractSpec spec)
            {
                if (spec.BaseContractFullyQualifiedName is string baseName
                    && _contractSpecs.TryGetValue(baseName, out ContractSpec baseSpec))
                {
                    Append(baseSpec);
                }

                foreach (MemberSpec member in spec.Members)
                {
                    flattened.Add((member, spec.ContractNamespace));
                }
            }
        }

        /// <summary>
        /// Whether this contract can be read back, which is a narrower question than whether it can
        /// be written.
        /// </summary>
        /// <remarks>
        /// Polymorphism and IsReference each need the read counterpart of machinery the write side
        /// already has, and both are ways to silently produce a graph that is not the one recorded -
        /// so they stay unreadable until they are implemented rather than approximated.
        /// </remarks>
        /// <summary>The name a diagnostic shows, which is the C# one rather than the emitted one.</summary>
        private static string DisplayName(ContractSpec contract) =>
            contract.FullyQualifiedName.StartsWith("global::", StringComparison.Ordinal)
                ? contract.FullyQualifiedName.Substring("global::".Length)
                : contract.FullyQualifiedName;

        private bool IsReadable(ContractSpec contract) => ReadBlocker(contract) is null;

        /// <summary>Why this contract cannot be read back, or null when it can.</summary>
        /// <remarks>
        /// A reason rather than a bool, because the answer is reported to the user as a warning and
        /// "it cannot be read" is not something anyone can act on. The reasons nest: a contract names
        /// the member that blocks it, which names the contract that blocks <em>that</em>, so the top
        /// line carries the whole chain down to the thing worth changing.
        /// </remarks>
        private string? ReadBlocker(ContractSpec contract)
        {
            if (_readBlockers.TryGetValue(contract.FullyQualifiedName, out string? known))
            {
                return known;
            }

            // A contract that reaches itself - a linked list is the ordinary case - is assumed
            // readable while its own answer is being computed. The recursion terminates at run time
            // on a nil or empty element, so the optimistic answer is the right one.
            _readBlockers[contract.FullyQualifiedName] = null;

            string? blocker = FindReadBlocker(contract);
            _readBlockers[contract.FullyQualifiedName] = blocker;
            return blocker;
        }

        private string? FindReadBlocker(ContractSpec contract)
        {
            if (!contract.IsSupported)
            {
                return "it is not written by generated code either";
            }

            if (!contract.HasParameterlessConstructor)
            {
                return "it has no accessible parameterless constructor, which generated code needs " +
                       "and DataContractSerializer does not";
            }

            if (!BaseChainIsKnown(contract))
            {
                return "a contract in its base chain was not collected";
            }

            // A document may announce a derived contract with i:type wherever this one is expected,
            // so reading this one means being able to read those too. Merely deriving from it does
            // not count: an i:type is resolved against the known types, so a descendant this contract
            // never names is one the reflection-based reader would refuse outright.
            foreach (string candidate in DerivedCandidates(contract))
            {
                if (ContractReadBlocker(candidate) is string derived)
                {
                    return "known type " + candidate + " " + derived;
                }
            }

            foreach ((MemberSpec member, string _) in FlattenedMembers(contract))
            {
                if (!member.IsSettable)
                {
                    return "member '" + member.MemberName + "' cannot be assigned";
                }

                if (MemberReadBlocker(member) is string blocked)
                {
                    return "member '" + member.MemberName + "' cannot be read back: " + blocked;
                }
            }

            return null;
        }

        /// <summary>The reason a named contract cannot be read, phrased to nest inside another.</summary>
        private string? ContractReadBlocker(string fullyQualifiedName)
        {
            if (!_contractSpecs.TryGetValue(fullyQualifiedName, out ContractSpec spec))
            {
                return "was not collected";
            }

            return ReadBlocker(spec) is string blocker ? "cannot be read back: " + blocker : null;
        }

        /// <summary>Whether every contract above this one in the base chain was collected.</summary>
        /// <remarks>
        /// A base the parser did not reach would leave its members out of the flattened list, and
        /// they would then read as elements the contract does not recognise - skipped in silence.
        /// </remarks>
        private bool BaseChainIsKnown(ContractSpec contract)
        {
            ContractSpec current = contract;
            while (current.BaseContractFullyQualifiedName is string baseName)
            {
                if (!_contractSpecs.TryGetValue(baseName, out ContractSpec baseSpec) || !baseSpec.IsSupported)
                {
                    return false;
                }

                current = baseSpec;
            }

            return true;
        }

        /// <summary>Why one member cannot be read back, or null when it can.</summary>
        private string? MemberReadBlocker(MemberSpec member)
        {
            if (member.Kind == MemberKind.Object)
            {
                foreach (string candidate in member.Candidates)
                {
                    if (ContractReadBlocker(candidate) is string blocked)
                    {
                        return "known type " + candidate + " " + blocked;
                    }
                }

                foreach (string enumCandidate in member.EnumCandidates)
                {
                    if (!_enumSpecs.ContainsKey(enumCandidate))
                    {
                        return "known enum " + enumCandidate + " was not collected";
                    }
                }

                return null;
            }

            if (member.EnumCandidates.Count > 0)
            {
                return "it names enum known types outside a boxed member";
            }

            if (member.Kind == MemberKind.Contract)
            {
                if (member.NestedContractFullyQualifiedName is not string nested)
                {
                    return "its contract type was not resolved";
                }

                if (ContractReadBlocker(nested) is string nestedBlocked)
                {
                    return nested + " " + nestedBlocked;
                }

                // Every contract the member may actually hold has to be readable, not just the one it
                // is declared as - the whole point of the i:type dispatch is that the others turn up
                // here too.
                foreach (string candidate in member.Candidates)
                {
                    if (ContractReadBlocker(candidate) is string blocked)
                    {
                        return "known type " + candidate + " " + blocked;
                    }
                }

                return null;
            }

            if (member.Kind == MemberKind.Collection)
            {
                if (member.ElementClrType is null)
                {
                    return "its collection type is not one the reader can build";
                }

                if (member.ElementKind == MemberKind.Collection)
                {
                    return member.NestedElementClrType is not null && IsBuiltInReadable(member.NestedElementKind)
                        ? null
                        : "its innermost item type is not one the reader can build";
                }

                if (member.ElementKind == MemberKind.Enum)
                {
                    return ReadEnumExpression(member.ElementEnumFullyQualifiedName, "__text") is not null
                        ? null
                        : "its item enum was not collected";
                }

                return IsBuiltInReadable(member.ElementKind)
                    ? null
                    : "its item type is not one the reader can build";
            }

            if (member.Kind == MemberKind.Dictionary)
            {
                return member.KeyClrType is not null
                    && member.ValueClrType is not null
                    && member.ItemNamespace is not null
                    && IsBuiltInReadable(member.KeyKind)
                    && IsBuiltInReadable(member.ValueKind)
                    ? null
                    : "its key or value type is not one the reader can build";
            }

            if (member.Kind == MemberKind.Enum)
            {
                return ReadEnumExpression(member.NestedContractFullyQualifiedName, "__text") is not null
                    ? null
                    : "its enum was not collected";
            }

            return IsBuiltInReadable(member.Kind)
                ? null
                : "its type is not one the reader can build";
        }

        /// <summary>Whether an element whose content is a built-in value can be read back.</summary>
        /// <remarks>
        /// Two families, because a byte array, a DateTimeOffset and a QName are not read from text
        /// at all - they consume the element themselves - and so have no text expression to offer.
        /// </remarks>
        private static bool IsBuiltInReadable(MemberKind kind) =>
            ElementValueExpression(kind) is not null || ReadValueExpression(kind, "__text") is not null;

        /// <summary>
        /// The expression that turns an element's text back into a member's value, or null when the
        /// kind is not one this slice reads.
        /// </summary>
        /// <remarks>
        /// The inverse of WriteValueStatement, and it has to stay that way: char went out as its
        /// numeric value so it comes back through an int, and DateTime needs RoundtripKind or the
        /// Utc flag the writer recorded is dropped on the way in.
        /// </remarks>
        private static string? ReadValueExpression(MemberKind kind, string text) => kind switch
        {
            MemberKind.Boolean => $"{XmlConvert}.ToBoolean({text})",
            MemberKind.Byte => $"{XmlConvert}.ToByte({text})",
            MemberKind.SByte => $"{XmlConvert}.ToSByte({text})",
            MemberKind.Int16 => $"{XmlConvert}.ToInt16({text})",
            MemberKind.UInt16 => $"{XmlConvert}.ToUInt16({text})",
            MemberKind.Int32 => $"{XmlConvert}.ToInt32({text})",
            MemberKind.UInt32 => $"{XmlConvert}.ToUInt32({text})",
            MemberKind.Int64 => $"{XmlConvert}.ToInt64({text})",
            MemberKind.UInt64 => $"{XmlConvert}.ToUInt64({text})",
            MemberKind.Single => $"{XmlConvert}.ToSingle({text})",
            MemberKind.Double => $"{XmlConvert}.ToDouble({text})",
            MemberKind.Decimal => $"{XmlConvert}.ToDecimal({text})",
            MemberKind.Char => $"(char){XmlConvert}.ToInt32({text})",
            MemberKind.String => text,
            MemberKind.Guid => $"{XmlConvert}.ToGuid({text})",
            MemberKind.TimeSpan => $"{XmlConvert}.ToTimeSpan({text})",
            MemberKind.DateTime =>
                $"{XmlConvert}.ToDateTime({text}, global::System.Xml.XmlDateTimeSerializationMode.RoundtripKind)",
            MemberKind.Uri => $"new global::System.Uri({text}, global::System.UriKind.RelativeOrAbsolute)",

            // Both decide their format at run time rather than at compile time, so the helper is
            // where the branch lives - see EmitDateOnlyHelpers.
            MemberKind.DateOnly => $"ReadDateOnly({text})",
            MemberKind.TimeOnly => $"ReadTimeOnly({text})",
            _ => null
        };

        /// <summary>
        /// Emits the reader shared by every generated serializer: the nil test and the element walk.
        /// </summary>
        /// <remarks>
        /// The walk mirrors ReflectionXmlFormatReader.ReflectionReadMembers, which scans forward
        /// only: a member can match an element only if it comes after the last one matched, and an
        /// element matching nothing is skipped rather than being an error. That is what makes an
        /// absent member keep its default and an unknown element harmless.
        /// </remarks>
        private void EmitReadHelpers(Indentor indentor)
        {
            _builder.AppendLine();
            _builder.AppendLine($"{indentor}private static bool IsNil({DictionaryReader} reader) =>");
            indentor.Increment();
            _builder.AppendLine($"{indentor}reader.GetAttribute(\"nil\", {Literal(SchemaInstanceNamespace)}) == \"true\";");
            indentor.Decrement();
            _builder.AppendLine();
            _builder.AppendLine($"{indentor}/// <summary>Reads an element's text, or null when it carries i:nil.</summary>");
            _builder.AppendLine($"{indentor}private static string ReadText({DictionaryReader} reader)");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            _builder.AppendLine($"{indentor}if (IsNil(reader))");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            _builder.AppendLine($"{indentor}reader.Skip();");
            _builder.AppendLine($"{indentor}return null;");
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
            _builder.AppendLine();
            _builder.AppendLine($"{indentor}return reader.ReadElementContentAsString();");
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
        }

        private void EmitNilHelper(Indentor indentor)
        {
            _builder.AppendLine();
            _builder.AppendLine($"{indentor}private static void WriteNil({DictionaryWriter} writer)");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            _builder.AppendLine($"{indentor}writer.WriteAttributeString(\"i\", \"nil\", {Literal(SchemaInstanceNamespace)}, \"true\");");
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
        }

        private string SerializerTypeName(ContractSpec contract) =>
            "__DataContractSerializer" + _contractIndexes[contract.FullyQualifiedName].ToString();

        private string ContentReaderName(ContractSpec contract) =>
            "__ReadContent" + _contractIndexes[contract.FullyQualifiedName].ToString();

        private string ContentWriterName(ContractSpec contract) => ContentWriterName(contract.FullyQualifiedName);

        private string ContentWriterName(string fullyQualifiedName) =>
            "__WriteContent" + _contractIndexes[fullyQualifiedName].ToString();

        private static string Literal(string value) => "\"" + value.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";
    }
