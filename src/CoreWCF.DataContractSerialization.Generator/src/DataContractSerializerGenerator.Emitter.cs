using System;
using System.Collections.Generic;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace CoreWCF.DataContractSerialization.Generator;

public sealed partial class DataContractSerializerGenerator
{
    /// <summary>
    /// Turns a <see cref="ContextSpec"/> into C# source. Sees no symbols and no compilation.
    /// </summary>
    /// <remarks>
    /// <para>
    /// The emitted writer calls mirror dotnet/runtime's ReflectionXmlFormatWriter and
    /// XmlWriterDelegator call for call. That is not stylistic: XmlDictionaryWriter assigns
    /// namespace prefixes as namespaces come into scope, so making the same calls in the same order
    /// reproduces the same prefixes - and the fixtures compare bytes.
    /// </para>
    /// <para>
    /// Each contract emits a static content writer that writes only its members, and a serializer
    /// class that wraps one in a root element. Splitting them is what lets a nested contract member
    /// be written inline - the wire format has no second wrapping element - and lets a derived
    /// contract emit its base's members first by simply calling the base writer.
    /// </para>
    /// </remarks>
    internal sealed class Emitter
    {
        private const string AotSerializer = "global::CoreWCF.Runtime.Serialization.AotXmlObjectSerializer";
        private const string DictionaryString = "global::System.Xml.XmlDictionaryString";
        private const string DictionaryWriter = "global::System.Xml.XmlDictionaryWriter";
        private const string XmlConvert = "global::System.Xml.XmlConvert";
        private const string SchemaInstanceNamespace = "http://www.w3.org/2001/XMLSchema-instance";
        private const string CollectionNamespace = Parser.CollectionNamespace;
        private const string SerializationNamespace = "http://schemas.microsoft.com/2003/10/Serialization/";
        private const string SchemaNamespace = "http://www.w3.org/2001/XMLSchema";
        private const string SystemContractNamespace = Parser.SystemContractNamespace;
        private const string ReferenceScope = "__ReferenceScope";

        private const string ReadScope = "__ReadScope";
        private const string DateOnlyIsPrimitive = "__DateOnlyIsPrimitive";
        private const string DictionaryReader = "global::System.Xml.XmlDictionaryReader";

        private readonly StringBuilder _builder = new();
        private readonly Dictionary<string, int> _contractIndexes = new(StringComparer.Ordinal);
        private readonly Dictionary<string, ContractSpec> _contractSpecs = new(StringComparer.Ordinal);
        private readonly Dictionary<string, int> _enumIndexes = new(StringComparer.Ordinal);
        private readonly Dictionary<string, EnumSpec> _enumSpecs = new(StringComparer.Ordinal);
        private readonly Dictionary<string, string?> _readBlockers = new(StringComparer.Ordinal);
        private readonly List<DiagnosticInfo> _diagnostics = new();

        /// <summary>Fallbacks found while emitting, reported once the source is built.</summary>
        /// <remarks>
        /// Produced here rather than by the parser because only the emitter knows the whole graph,
        /// and readability is a property of the graph rather than of one contract.
        /// </remarks>
        internal IReadOnlyList<DiagnosticInfo> Diagnostics => _diagnostics;

        internal SourceText Emit(ContextSpec context)
        {
            Indentor indentor = new();

            int index = 0;
            foreach (ContractSpec contract in context.Contracts)
            {
                _contractIndexes[contract.FullyQualifiedName] = index++;
                _contractSpecs[contract.FullyQualifiedName] = contract;
            }

            _builder.AppendLine("// <auto-generated>");
            _builder.AppendLine("// Generated by the CoreWCF.DataContractSerialization source generator. DO NOT EDIT!");
            _builder.AppendLine("// </auto-generated>");
            // The consuming project's nullable setting is not ours to guess at, and generated code
            // that tripped a nullable warning would fail builds that treat warnings as errors.
            _builder.AppendLine("#nullable disable");
            _builder.AppendLine();

            bool hasNamespace = context.Namespace is not null;
            if (hasNamespace)
            {
                _builder.AppendLine($"namespace {context.Namespace}");
                _builder.AppendLine("{");
                indentor.Increment();
            }

            _builder.AppendLine($"{indentor}partial class {context.Name}");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();

            int enumIndex = 0;
            foreach (EnumSpec enumSpec in context.Enums)
            {
                _enumIndexes[enumSpec.FullyQualifiedName] = enumIndex++;
                _enumSpecs[enumSpec.FullyQualifiedName] = enumSpec;
            }

            EmitGetSerializer(indentor, context);
            _builder.AppendLine();
            EmitCoversKnownTypes(indentor, context);
            EmitNilHelper(indentor);
            EmitDateTimeOffsetHelper(indentor);
            EmitDateTimeOffsetReadHelper(indentor);
            EmitQNameHelper(indentor);
            EmitQNameReadHelper(indentor);
            EmitXsiTypeReadHelper(indentor);
            EmitBoxedValueReadHelper(indentor);
            EmitDateOnlyHelpers(indentor);
            EmitReadHelpers(indentor);
            EmitAnyTypeHelper(indentor);
            EmitReferenceScope(indentor);
            EmitReadScope(indentor);

            if (context.Enums.Count > 0)
            {
                EmitEnumHelper(indentor);
                EmitEnumReadHelper(indentor);

                foreach (EnumSpec enumSpec in context.Enums)
                {
                    _builder.AppendLine();
                    EmitEnumTable(indentor, enumSpec);
                }
            }

            foreach (ContractSpec contract in context.Contracts)
            {
                if (!contract.IsSupported)
                {
                    // Only for the types the user listed. A nested contract that cannot be written
                    // makes its container unsupported too, so reporting both would bury the one line
                    // they can act on under a cascade of consequences.
                    if (contract.IsRoot)
                    {
                        _diagnostics.Add(DiagnosticInfo.Create(
                            DiagnosticDescriptors.FallsBackToReflection,
                            contract.Location,
                            DisplayName(contract),
                            string.Join("; ", contract.UnsupportedReasons)));
                    }

                    continue;
                }

                _builder.AppendLine();
                EmitContentWriter(indentor, contract);

                if (ReadBlocker(contract) is string readBlocker)
                {
                    if (contract.IsRoot)
                    {
                        _diagnostics.Add(DiagnosticInfo.Create(
                            DiagnosticDescriptors.ReadFallsBackToReflection,
                            contract.Location,
                            DisplayName(contract),
                            readBlocker));
                    }
                }
                else
                {
                    _builder.AppendLine();
                    EmitContentReader(indentor, contract);
                }

                if (contract.IsRoot)
                {
                    _builder.AppendLine();
                    EmitSerializer(indentor, contract);
                }
            }

            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");

            if (hasNamespace)
            {
                indentor.Decrement();
                _builder.AppendLine("}");
            }

            _builder.AppendLine();
            _builder.AppendLine("#nullable restore");

            return SourceText.From(_builder.ToString(), Encoding.UTF8, SourceHashAlgorithm.Sha256);
        }

        private void EmitGetSerializer(Indentor indentor, ContextSpec context)
        {
            _builder.AppendLine($"{indentor}/// <inheritdoc />");
            _builder.AppendLine($"{indentor}public override {AotSerializer} GetSerializer(global::System.Type type, {DictionaryString} name, {DictionaryString} ns)");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();

            foreach (ContractSpec contract in context.Contracts)
            {
                if (contract.IsSupported && contract.IsRoot)
                {
                    _builder.AppendLine($"{indentor}if (type == typeof({contract.FullyQualifiedName}))");
                    _builder.AppendLine($"{indentor}{{");
                    indentor.Increment();
                    _builder.AppendLine($"{indentor}return new {SerializerTypeName(contract)}(name, ns);");
                    indentor.Decrement();
                    _builder.AppendLine($"{indentor}}}");
                    _builder.AppendLine();
                }
                else if (!contract.IsSupported)
                {
                    // Recorded rather than silently omitted: this list is the coverage report, and
                    // every reason goes in it rather than only the first. One line per contract
                    // understates the work whenever a contract is blocked on several things.
                    foreach (string reason in contract.UnsupportedReasons)
                    {
                        _builder.AppendLine($"{indentor}// {contract.FullyQualifiedName}: {reason}");
                    }
                }
            }

            // Null is a supported answer: CoreWCF falls back to the reflection-based serializer for
            // anything this context does not cover.
            _builder.AppendLine($"{indentor}return null;");

            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
        }

        /// <summary>
        /// Emits the answer to "does the serializer for this type already resolve these known
        /// types?", from the <c>[KnownType]</c> closure each root was compiled against.
        /// </summary>
        /// <remarks>
        /// The test is subset, not equality: an operation that supplies fewer known types than the
        /// attributes declare is still fully covered. Anything beyond the closure is a type this
        /// serializer has no branch for, so the honest answer is false and the caller falls back.
        /// </remarks>
        private void EmitCoversKnownTypes(Indentor indentor, ContextSpec context)
        {
            _builder.AppendLine($"{indentor}/// <inheritdoc />");
            _builder.AppendLine($"{indentor}public override bool CoversKnownTypes(global::System.Type type, global::System.Collections.Generic.IList<global::System.Type> knownTypes)");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            _builder.AppendLine($"{indentor}if (knownTypes == null || knownTypes.Count == 0)");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            _builder.AppendLine($"{indentor}return true;");
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");

            foreach (ContractSpec contract in context.Contracts)
            {
                if (!contract.IsSupported || !contract.IsRoot || contract.KnownTypes.Count == 0)
                {
                    continue;
                }

                _builder.AppendLine();
                _builder.AppendLine($"{indentor}if (type == typeof({contract.FullyQualifiedName}))");
                _builder.AppendLine($"{indentor}{{");
                indentor.Increment();
                _builder.AppendLine($"{indentor}for (int i = 0; i < knownTypes.Count; i++)");
                _builder.AppendLine($"{indentor}{{");
                indentor.Increment();

                bool first = true;
                foreach (string knownType in contract.KnownTypes)
                {
                    string keyword = first ? "if" : "else if";
                    first = false;
                    _builder.AppendLine($"{indentor}{keyword} (knownTypes[i] == typeof({knownType})) {{ continue; }}");
                }

                _builder.AppendLine($"{indentor}return false;");
                indentor.Decrement();
                _builder.AppendLine($"{indentor}}}");
                _builder.AppendLine();
                _builder.AppendLine($"{indentor}return true;");
                indentor.Decrement();
                _builder.AppendLine($"{indentor}}}");
            }

            _builder.AppendLine();
            _builder.AppendLine($"{indentor}return false;");
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
        }

        private void EmitSerializer(Indentor indentor, ContractSpec contract)
        {
            string typeName = SerializerTypeName(contract);

            _builder.AppendLine($"{indentor}/// <summary>Writes {contract.ContractName} in {contract.ContractNamespace}.</summary>");
            _builder.AppendLine($"{indentor}private sealed class {typeName} : {AotSerializer}");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();

            _builder.AppendLine($"{indentor}private readonly {DictionaryString} _name;");
            _builder.AppendLine($"{indentor}private readonly {DictionaryString} _ns;");
            _builder.AppendLine();
            _builder.AppendLine($"{indentor}internal {typeName}({DictionaryString} name, {DictionaryString} ns)");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            _builder.AppendLine($"{indentor}_name = name;");
            _builder.AppendLine($"{indentor}_ns = ns;");
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
            _builder.AppendLine();

            _builder.AppendLine($"{indentor}/// <inheritdoc />");
            _builder.AppendLine($"{indentor}public override void WriteObject({DictionaryWriter} writer, object graph)");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();

            _builder.AppendLine($"{indentor}writer.WriteStartElement(_name, _ns);");
            _builder.AppendLine();

            // The contract namespace is declared at the root with no prefix, letting the writer
            // allocate one - this is what produces 'a:'. Skipped when it would duplicate the root
            // namespace. Mirrors XmlObjectSerializer.CheckIfNeedsContractNsAtRoot.
            _builder.AppendLine($"{indentor}if (!string.Equals({Literal(contract.ContractNamespace)}, _ns?.Value, global::System.StringComparison.Ordinal))");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            _builder.AppendLine($"{indentor}writer.WriteXmlnsAttribute(null, {Literal(contract.ContractNamespace)});");
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
            _builder.AppendLine();

            // Declared on every root even when unused, matching
            // XmlObjectSerializerWriteContext.HandleGraphAtTopLevel.
            _builder.AppendLine($"{indentor}writer.WriteXmlnsAttribute(\"i\", {Literal(SchemaInstanceNamespace)});");
            _builder.AppendLine();

            _builder.AppendLine($"{indentor}if (graph == null)");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            _builder.AppendLine($"{indentor}WriteNil(writer);");
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
            _builder.AppendLine($"{indentor}else");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();

            // One scope per WriteObject call, so ids restart at i1 for every document and nothing
            // survives between calls. Its table is allocated on first use, so a graph with no
            // reference-preserving contract in it pays nothing but the empty object.
            _builder.AppendLine($"{indentor}{ReferenceScope} scope = new {ReferenceScope}();");

            // The root can hold a derived contract just as a member can, and it has no member to
            // carry the decision. Without this the graph would be written through the declared
            // contract's writer, dropping every member the derived one adds and reporting success.
            EquatableArray<string> rootCandidates = DerivedCandidates(contract);

            if (rootCandidates.Count > 0)
            {
                _builder.AppendLine($"{indentor}global::System.Type __runtimeType = graph.GetType();");
                _builder.AppendLine();
                _builder.AppendLine($"{indentor}if (__runtimeType == typeof({contract.FullyQualifiedName}))");
                _builder.AppendLine($"{indentor}{{");
                indentor.Increment();
                EmitRootContentCall(indentor, contract, contract);
                indentor.Decrement();
                _builder.AppendLine($"{indentor}}}");

                foreach (string candidate in rootCandidates)
                {
                    ContractSpec spec = _contractSpecs[candidate];

                    _builder.AppendLine($"{indentor}else if (__runtimeType == typeof({candidate}))");
                    _builder.AppendLine($"{indentor}{{");
                    indentor.Increment();
                    EmitXsiType(indentor, spec);
                    EmitRootContentCall(indentor, spec, contract);
                    indentor.Decrement();
                    _builder.AppendLine($"{indentor}}}");
                }

                _builder.AppendLine($"{indentor}else");
                _builder.AppendLine($"{indentor}{{");
                indentor.Increment();
                _builder.AppendLine($"{indentor}throw new global::System.Runtime.Serialization.SerializationException(");
                indentor.Increment();
                _builder.AppendLine($"{indentor}\"Type '\" + __runtimeType + \"' with data contract name '\" + __runtimeType.Name +");
                _builder.AppendLine($"{indentor}\"' is not expected. Add any types not known statically to the list of known types.\");");
                indentor.Decrement();
                indentor.Decrement();
                _builder.AppendLine($"{indentor}}}");
            }
            else
            {
                EmitRootContentCall(indentor, contract, contract);
            }
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
            _builder.AppendLine();
            _builder.AppendLine($"{indentor}writer.WriteEndElement();");

            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");

            if (IsReadable(contract))
            {
                EmitReadObject(indentor, contract);
            }

            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
        }

        /// <summary>
        /// Emits the root's call into a contract's content writer, with its id if it keeps one.
        /// </summary>
        /// <remarks>
        /// The root is by definition the first sight of this instance, so WriteIdOrRef always writes
        /// z:Id and never z:Ref - but it goes through the same path so that the id counter sees it,
        /// which is what makes the root i1 and the first member i2. It comes after the xmlns
        /// declarations because that is where OnHandleIsReference sits relative to
        /// HandleGraphAtTopLevel in dotnet/runtime; the writer emits attributes ahead of namespace
        /// declarations, which is what puts z:Id first in the output.
        /// </remarks>
        private void EmitRootContentCall(Indentor indentor, ContractSpec runtime, ContractSpec declared)
        {
            if (runtime.IsReference)
            {
                _builder.AppendLine($"{indentor}scope.WriteIdOrRef(writer, graph);");
            }

            _builder.AppendLine($"{indentor}{ContentWriterName(runtime)}(writer, ({runtime.FullyQualifiedName})graph, scope);");
        }

        /// <summary>
        /// Emits the read side of a serializer: the opt-in flag, the start test and ReadObject.
        /// </summary>
        /// <remarks>
        /// <c>CanReadObject</c> is false on the base class, so a contract this slice does not cover
        /// never claims to read and the caller keeps the reflection-based serializer. That is the
        /// same shape as GetSerializer returning null, one level down.
        /// </remarks>
        private void EmitReadObject(Indentor indentor, ContractSpec contract)
        {
            _builder.AppendLine();
            _builder.AppendLine($"{indentor}/// <inheritdoc />");
            _builder.AppendLine($"{indentor}public override bool CanReadObject => true;");
            _builder.AppendLine();
            _builder.AppendLine($"{indentor}/// <inheritdoc />");
            _builder.AppendLine($"{indentor}public override bool IsStartObject({DictionaryReader} reader)");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            _builder.AppendLine($"{indentor}reader.MoveToContent();");
            _builder.AppendLine($"{indentor}return reader.IsStartElement(_name, _ns);");
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
            _builder.AppendLine();
            _builder.AppendLine($"{indentor}/// <inheritdoc />");
            _builder.AppendLine($"{indentor}public override object ReadObject({DictionaryReader} reader, bool verifyObjectName)");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            _builder.AppendLine($"{indentor}reader.MoveToContent();");
            _builder.AppendLine();
            _builder.AppendLine($"{indentor}if (verifyObjectName && !reader.IsStartElement(_name, _ns))");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            _builder.AppendLine($"{indentor}throw new global::System.Runtime.Serialization.SerializationException(");
            indentor.Increment();
            _builder.AppendLine($"{indentor}\"Expecting element '\" + _name.Value + \"' from namespace '\" + _ns.Value + \"'.\");");
            indentor.Decrement();
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
            _builder.AppendLine();
            _builder.AppendLine($"{indentor}if (IsNil(reader))");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            _builder.AppendLine($"{indentor}reader.Skip();");
            _builder.AppendLine($"{indentor}return null;");
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
            _builder.AppendLine();
            // The root is polymorphic for the same reason a member is - a document may announce a
            // derived contract with i:type - and it has no member to carry the decision, so it makes
            // it here.
            EquatableArray<string> candidates = DerivedCandidates(contract);

            // One scope per ReadObject call, so ids restart with every document and nothing survives
            // between calls - the mirror of what WriteObject does with its own.
            _builder.AppendLine($"{indentor}{ReadScope} scope = new {ReadScope}();");
            _builder.AppendLine($"{indentor}{contract.FullyQualifiedName} result = default;");
            _builder.AppendLine();

            if (candidates.Count > 0)
            {
                EmitDispatchedRead(indentor, contract, candidates, "result");
            }
            else
            {
                EmitTypedContractRead(indentor, contract, "result");
            }

            _builder.AppendLine();
            _builder.AppendLine($"{indentor}return result;");
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
        }

        /// <summary>
        /// Emits the method that writes a contract's members, with no wrapping element.
        /// </summary>
        private void EmitContentWriter(Indentor indentor, ContractSpec contract)
        {
            _builder.AppendLine($"{indentor}/// <summary>Writes the members of {contract.ContractName}, without a wrapping element.</summary>");
            _builder.AppendLine($"{indentor}private static void {ContentWriterName(contract)}({DictionaryWriter} writer, {contract.FullyQualifiedName} value, {ReferenceScope} scope)");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();

            if (contract.BaseContractFullyQualifiedName is string baseName && _contractIndexes.ContainsKey(baseName))
            {
                // Base members come first, and are ordered within their own contract rather than
                // merged with the derived ones. Mirrors the recursion in
                // ReflectionXmlClassWriter.ReflectionWriteMembers. The object's id belongs to the
                // element that wraps it, not to a level of its base chain, so nothing about
                // references happens here - it was already decided by the caller.
                _builder.AppendLine($"{indentor}{ContentWriterName(baseName)}(writer, value, scope);");

                if (contract.Members.Count > 0)
                {
                    _builder.AppendLine();
                }
            }

            if (contract.Members.Count == 0 && contract.BaseContractFullyQualifiedName is null)
            {
                _builder.AppendLine($"{indentor}// no data members");
            }

            bool first = true;
            foreach (MemberSpec member in contract.Members)
            {
                if (!first)
                {
                    _builder.AppendLine();
                }

                first = false;
                EmitMember(indentor, contract, member);
            }

            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
        }

        private void EmitMember(Indentor indentor, ContractSpec contract, MemberSpec member)
        {
            string access = "value." + member.MemberName;
            string name = Literal(member.Name);

            _builder.AppendLine($"{indentor}// {member.MemberName} (Order = {member.Order})");

            if (!member.EmitDefaultValue)
            {
                // A member equal to its type's default is omitted entirely - unless it is also
                // required, which DataContractSerializer treats as an error rather than an omission.
                // See ReflectionXmlFormatWriter.ReflectionWriteMembers.
                _builder.AppendLine($"{indentor}if ({IsDefaultExpression(member, access)})");
                _builder.AppendLine($"{indentor}{{");
                indentor.Increment();

                if (member.IsRequired)
                {
                    _builder.AppendLine($"{indentor}throw new global::System.Runtime.Serialization.SerializationException(");
                    indentor.Increment();
                    _builder.AppendLine($"{indentor}\"Member {member.MemberName} is required but is at its default value and EmitDefaultValue is false.\");");
                    indentor.Decrement();
                }
                else
                {
                    _builder.AppendLine($"{indentor}// omitted");
                }

                indentor.Decrement();
                _builder.AppendLine($"{indentor}}}");
                _builder.AppendLine($"{indentor}else");
                _builder.AppendLine($"{indentor}{{");
                indentor.Increment();

                // Reaching this branch already proves the member is not at its default, and for the
                // nullable kinds "default" is exactly "null" - so re-testing for null here would be
                // dead code.
                EmitMemberElement(indentor, contract, member, access, name, nullAlreadyExcluded: true);

                indentor.Decrement();
                _builder.AppendLine($"{indentor}}}");
            }
            else
            {
                EmitMemberElement(indentor, contract, member, access, name, nullAlreadyExcluded: false);
            }
        }

        private void EmitMemberElement(Indentor indentor, ContractSpec contract, MemberSpec member, string access, string name, bool nullAlreadyExcluded)
        {
            bool canBeNull = !nullAlreadyExcluded
                && (member.IsNullableValueType
                    || member.Kind is MemberKind.String or MemberKind.ByteArray or MemberKind.Contract
                        or MemberKind.Collection or MemberKind.Dictionary or MemberKind.Object or MemberKind.Uri or MemberKind.QName);

            // An XmlQualifiedName member is the one case where the element carries a prefix of its
            // own rather than reusing whatever the writer has bound. Mirrors NeedsPrefix in
            // ReflectionXmlFormatWriter, which forces Globals.ElementPrefix for exactly this type
            // and only when the namespace is non-empty. The result is a second prefix bound to the
            // contract's namespace alongside the one already in scope, which looks redundant and is
            // what the serializer does.
            //
            // A null one does not get it. The prefix belongs to the path that writes a value, and a
            // null member never reaches it - it is written by WriteNull, which opens the element
            // with whatever prefix is already bound. Both halves are pinned by fixtures:
            // SanityQualifiedNames records the null case and AllTypes the value case.
            bool needsPrefix = member.Kind == MemberKind.QName && contract.ContractNamespace.Length > 0;
            string prefixed = $"writer.WriteStartElement(\"q\", {name}, {Literal(contract.ContractNamespace)});";
            string plain = $"writer.WriteStartElement({name}, {Literal(contract.ContractNamespace)});";

            if (needsPrefix && canBeNull)
            {
                _builder.AppendLine($"{indentor}if ({access} == null)");
                _builder.AppendLine($"{indentor}{{");
                indentor.Increment();
                _builder.AppendLine($"{indentor}{plain}");
                indentor.Decrement();
                _builder.AppendLine($"{indentor}}}");
                _builder.AppendLine($"{indentor}else");
                _builder.AppendLine($"{indentor}{{");
                indentor.Increment();
                _builder.AppendLine($"{indentor}{prefixed}");
                indentor.Decrement();
                _builder.AppendLine($"{indentor}}}");
            }
            else
            {
                _builder.AppendLine($"{indentor}{(needsPrefix ? prefixed : plain)}");
            }

            // A member whose type lives in a different contract namespace declares it here rather
            // than at the root. Mirrors ClassDataContract.GetChildNamespaceToDeclare, and is what
            // puts xmlns:b on the member element.
            if (member.ChildNamespaceToDeclare is string childNamespace)
            {
                // DateOnly and TimeOnly only declare it where the serializer does not recognise
                // them and falls back to writing a memberless contract. Where it does, they are
                // primitives and the element carries nothing but its value.
                bool onlyWhenUnrecognised = member.Kind is MemberKind.DateOnly or MemberKind.TimeOnly;

                if (onlyWhenUnrecognised)
                {
                    _builder.AppendLine($"{indentor}if (!{DateOnlyIsPrimitive})");
                    _builder.AppendLine($"{indentor}{{");
                    indentor.Increment();
                }

                _builder.AppendLine($"{indentor}writer.WriteXmlnsAttribute(null, {Literal(childNamespace)});");

                if (onlyWhenUnrecognised)
                {
                    indentor.Decrement();
                    _builder.AppendLine($"{indentor}}}");
                }
            }

            if (canBeNull)
            {
                string nullTest = member.IsNullableValueType ? $"!{access}.HasValue" : $"{access} == null";
                _builder.AppendLine($"{indentor}if ({nullTest})");
                _builder.AppendLine($"{indentor}{{");
                indentor.Increment();
                _builder.AppendLine($"{indentor}WriteNil(writer);");
                indentor.Decrement();
                _builder.AppendLine($"{indentor}}}");
                _builder.AppendLine($"{indentor}else");
                _builder.AppendLine($"{indentor}{{");
                indentor.Increment();
            }

            string value = member.IsNullableValueType ? access + ".Value" : access;

            if (member.Kind == MemberKind.Object)
            {
                EmitObjectMember(indentor, member, value);
            }
            else if (member.Kind == MemberKind.Contract && member.Candidates.Count > 0)
            {
                EmitPolymorphicMember(indentor, member, value);
            }
            else if (member.Kind == MemberKind.Contract)
            {
                string nested = member.NestedContractFullyQualifiedName!;

                if (_contractSpecs.TryGetValue(nested, out ContractSpec nestedSpec) && nestedSpec.IsReference)
                {
                    // First sight writes z:Id and the members; a repeat writes z:Ref and nothing
                    // else, which is what stops a cycle from recursing. Mirrors
                    // XmlObjectSerializerWriteContext.OnHandleIsReference, whose true result means
                    // "already written, do not write it again".
                    _builder.AppendLine($"{indentor}if (!scope.WriteIdOrRef(writer, {value}))");
                    _builder.AppendLine($"{indentor}{{");
                    indentor.Increment();
                    _builder.AppendLine($"{indentor}{ContentWriterName(nested)}(writer, {value}, scope);");
                    indentor.Decrement();
                    _builder.AppendLine($"{indentor}}}");
                }
                else
                {
                    EmitByValueContentCall(indentor, nested, value, value);
                }
            }
            else if (member.Kind == MemberKind.Dictionary)
            {
                EmitDictionaryMember(indentor, member, value);
            }
            else if (member.Kind == MemberKind.Collection)
            {
                // Items go in the collection namespace, not the containing contract's, and each is
                // named after its XSD type. An empty collection writes no children at all, which is
                // why the member element is still opened before this loop.
                _builder.AppendLine($"{indentor}foreach (var item in {value})");
                _builder.AppendLine($"{indentor}{{");
                indentor.Increment();
                _builder.AppendLine($"{indentor}writer.WriteStartElement({Literal(member.ItemName!)}, {Literal(member.ItemNamespace ?? CollectionNamespace)});");

                if (member.ElementCanBeNull)
                {
                    _builder.AppendLine($"{indentor}if (item == null)");
                    _builder.AppendLine($"{indentor}{{");
                    indentor.Increment();
                    _builder.AppendLine($"{indentor}WriteNil(writer);");
                    indentor.Decrement();
                    _builder.AppendLine($"{indentor}}}");
                    _builder.AppendLine($"{indentor}else");
                    _builder.AppendLine($"{indentor}{{");
                    indentor.Increment();
                }

                if (member.ElementKind == MemberKind.Enum)
                {
                    EmitWriteEnum(indentor, member.ElementEnumFullyQualifiedName!, "item");
                }
                else if (member.ElementKind == MemberKind.Object)
                {
                    // An ArrayList item announces its own runtime type, and writes its own i:nil.
                    _builder.AppendLine($"{indentor}WriteAnyType(writer, item);");
                }
                else if (member.ElementKind == MemberKind.Collection)
                {
                    // A jagged item is an array in its own right: the ArrayOf element is already
                    // open, and its children are the innermost items, in the same namespace.
                    _builder.AppendLine($"{indentor}foreach (var innerItem in item)");
                    _builder.AppendLine($"{indentor}{{");
                    indentor.Increment();
                    _builder.AppendLine($"{indentor}writer.WriteStartElement({Literal(member.NestedItemName!)}, {Literal(member.ItemNamespace ?? CollectionNamespace)});");

                    if (member.NestedElementCanBeNull)
                    {
                        _builder.AppendLine($"{indentor}if (innerItem == null)");
                        _builder.AppendLine($"{indentor}{{");
                        indentor.Increment();
                        _builder.AppendLine($"{indentor}WriteNil(writer);");
                        indentor.Decrement();
                        _builder.AppendLine($"{indentor}}}");
                        _builder.AppendLine($"{indentor}else");
                        _builder.AppendLine($"{indentor}{{");
                        indentor.Increment();
                    }

                    _builder.AppendLine($"{indentor}{WriteValueStatement(member.NestedElementKind, "innerItem")}");

                    if (member.NestedElementCanBeNull)
                    {
                        indentor.Decrement();
                        _builder.AppendLine($"{indentor}}}");
                    }

                    _builder.AppendLine($"{indentor}writer.WriteEndElement();");
                    indentor.Decrement();
                    _builder.AppendLine($"{indentor}}}");
                }
                else
                {
                    _builder.AppendLine($"{indentor}{WriteValueStatement(member.ElementKind, "item")}");
                }

                if (member.ElementCanBeNull)
                {
                    indentor.Decrement();
                    _builder.AppendLine($"{indentor}}}");
                }

                _builder.AppendLine($"{indentor}writer.WriteEndElement();");
                indentor.Decrement();
                _builder.AppendLine($"{indentor}}}");
            }
            else if (member.Kind == MemberKind.Enum)
            {
                EmitWriteEnum(indentor, member.NestedContractFullyQualifiedName!, value);
            }
            else
            {
                _builder.AppendLine($"{indentor}{WriteValueStatement(member.Kind, value)}");
            }

            if (canBeNull)
            {
                indentor.Decrement();
                _builder.AppendLine($"{indentor}}}");
            }

            _builder.AppendLine($"{indentor}writer.WriteEndElement();");
        }

        /// <summary>
        /// Emits a member that may hold any of several contracts, chosen by runtime type.
        /// </summary>
        /// <remarks>
        /// <para>
        /// The branch is on exact type equality rather than a type pattern, because a pattern would
        /// let a base contract's branch swallow a derived instance depending on the order the
        /// candidates happen to be in. Exact equality makes the emitted code order-independent and
        /// matches what the serializer does, which is to look up the runtime type's contract.
        /// </para>
        /// <para>
        /// i:type is written for every candidate except the declared type, mirroring
        /// XmlObjectSerializerWriteContext.WriteTypeInfo, which emits it only when the runtime
        /// contract differs from the declared one. It goes on before any z:Id because that is the
        /// order the two sit in upstream: WriteTypeInfo runs in SerializeWithXsiType, and
        /// OnHandleIsReference runs later, inside the class writer it delegates to.
        /// </para>
        /// <para>
        /// A runtime type outside the set throws, exactly as the reflection path does with
        /// DcTypeNotFoundOnSerialize. Falling back is not an option here: by this point the element
        /// is already open and half a document has been written.
        /// </para>
        /// </remarks>
        private void EmitPolymorphicMember(Indentor indentor, MemberSpec member, string value)
        {
            string declared = member.NestedContractFullyQualifiedName!;
            string local = "__runtimeType";

            _builder.AppendLine($"{indentor}global::System.Type {local} = {value}.GetType();");

            bool first = true;
            foreach (string candidate in member.Candidates)
            {
                ContractSpec spec = _contractSpecs[candidate];

                _builder.AppendLine($"{indentor}{(first ? "if" : "else if")} ({local} == typeof({candidate}))");
                _builder.AppendLine($"{indentor}{{");
                indentor.Increment();
                first = false;

                if (!string.Equals(candidate, declared, StringComparison.Ordinal))
                {
                    EmitXsiType(indentor, spec);
                }

                string typed = $"(({candidate}){value})";

                if (spec.IsReference)
                {
                    _builder.AppendLine($"{indentor}if (!scope.WriteIdOrRef(writer, {value}))");
                    _builder.AppendLine($"{indentor}{{");
                    indentor.Increment();
                    _builder.AppendLine($"{indentor}{ContentWriterName(candidate)}(writer, {typed}, scope);");
                    indentor.Decrement();
                    _builder.AppendLine($"{indentor}}}");
                }
                else
                {
                    EmitByValueContentCall(indentor, candidate, value, typed);
                }

                indentor.Decrement();
                _builder.AppendLine($"{indentor}}}");
            }

            _builder.AppendLine($"{indentor}else");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            _builder.AppendLine($"{indentor}throw new global::System.Runtime.Serialization.SerializationException(");
            indentor.Increment();
            _builder.AppendLine($"{indentor}\"Type '\" + {local}.FullName + \"' is not among the known types for this contract.\");");
            indentor.Decrement();
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
        }

        /// <summary>
        /// Emits a dictionary member: one entry element per pair, each with a Key and a Value.
        /// </summary>
        /// <remarks>
        /// The entry element is named after both type arguments - KeyValueOfstringstring,
        /// KeyValueOfbase64Binarybase64Binary - and every element involved sits in the Arrays
        /// namespace, declared once on the member. Key and Value are ordinary primitive writes, so a
        /// nullable one gets i:nil exactly as a member of that type would.
        /// </remarks>
        private void EmitDictionaryMember(Indentor indentor, MemberSpec member, string value)
        {
            _builder.AppendLine($"{indentor}foreach (var pair in {value})");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            _builder.AppendLine($"{indentor}writer.WriteStartElement({Literal(member.ItemName!)}, {Literal(member.ItemNamespace!)});");

            EmitDictionaryPart(indentor, "Key", member.ItemNamespace!, member.KeyKind, member.KeyCanBeNull, "pair.Key");
            EmitDictionaryPart(indentor, "Value", member.ItemNamespace!, member.ValueKind, member.ValueCanBeNull, "pair.Value");

            _builder.AppendLine($"{indentor}writer.WriteEndElement();");
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
        }

        private void EmitDictionaryPart(Indentor indentor, string name, string ns, MemberKind kind, bool canBeNull, string access)
        {
            _builder.AppendLine($"{indentor}writer.WriteStartElement({Literal(name)}, {Literal(ns)});");

            if (canBeNull)
            {
                _builder.AppendLine($"{indentor}if ({access} == null)");
                _builder.AppendLine($"{indentor}{{");
                indentor.Increment();
                _builder.AppendLine($"{indentor}WriteNil(writer);");
                indentor.Decrement();
                _builder.AppendLine($"{indentor}}}");
                _builder.AppendLine($"{indentor}else");
                _builder.AppendLine($"{indentor}{{");
                indentor.Increment();
            }

            _builder.AppendLine($"{indentor}{WriteValueStatement(kind, access)}");

            if (canBeNull)
            {
                indentor.Decrement();
                _builder.AppendLine($"{indentor}}}");
            }

            _builder.AppendLine($"{indentor}writer.WriteEndElement();");
        }

        /// <summary>
        /// Emits a nested contract write, guarded against cycles when it is written by value.
        /// </summary>
        /// <remarks>
        /// A reference-preserving contract cannot recurse forever - the second sight of an instance
        /// is a z:Ref with no content - so only the by-value path needs the guard. Mirrors
        /// XmlObjectSerializerWriteContext.OnHandleReference, which only starts tracking past a
        /// depth of 512 and then throws CannotSerializeObjectWithCycles if the object is already on
        /// the path. Without it the generated writer would recurse until the stack ran out, turning
        /// a catchable exception into a process-killing StackOverflowException.
        /// </remarks>
        private void EmitByValueContentCall(Indentor indentor, string candidate, string value, string typed)
        {
            _builder.AppendLine($"{indentor}scope.EnterByValue({value});");
            _builder.AppendLine($"{indentor}{ContentWriterName(candidate)}(writer, {typed}, scope);");
            _builder.AppendLine($"{indentor}scope.ExitByValue({value});");
        }

        /// <summary>
        /// Emits the call that writes one enum value from its table.
        /// </summary>
        /// <remarks>
        /// The cast is where the backing type matters: a ulong-backed enum has to reinterpret its
        /// bits rather than convert them, or every value past long.MaxValue becomes a different
        /// number. Mirrors EnumDataContract's use of Convert.ToUInt64 for those enums.
        /// </remarks>
        private void EmitWriteEnum(Indentor indentor, string enumFullyQualifiedName, string value)
        {
            int index = _enumIndexes[enumFullyQualifiedName];
            EnumSpec spec = _enumSpecs[enumFullyQualifiedName];
            string cast = spec.IsUnsignedLong ? $"unchecked((long)(ulong){value})" : $"(long){value}";
            string isFlags = spec.IsFlags ? "true" : "false";

            _builder.AppendLine($"{indentor}WriteEnum(writer, {cast}, __EnumValues{index}, __EnumNames{index}, {isFlags}, {Literal(enumFullyQualifiedName)});");
        }

        /// <summary>
        /// Emits a member declared as <c>object</c>, whose runtime type decides everything.
        /// </summary>
        /// <remarks>
        /// <para>
        /// Three shapes are not a boxed primitive and each is written differently, which the
        /// SanityBoxedPrimitives fixture pins: a bare <c>object</c> is anyType and writes an empty
        /// element with no i:type at all; null is i:nil with no i:type; and a data contract writes
        /// i:type plus its members.
        /// </para>
        /// <para>
        /// The type names come from that same fixture rather than from memory. Most are XML Schema
        /// names, but char, Guid and TimeSpan have no XSD equivalent and are named in the
        /// serialization namespace instead - a split that is invisible until a document is compared
        /// byte for byte.
        /// </para>
        /// <para>
        /// A runtime type outside the switch throws. DataContractSerializer would accept some of
        /// them - arrays and collections are always allowed in an object member - so this is a
        /// narrower contract than the reflection path, recorded in the risk register.
        /// </para>
        /// </remarks>
        private void EmitObjectMember(Indentor indentor, MemberSpec member, string value)
        {
            _builder.AppendLine($"{indentor}global::System.Type __runtimeType = {value}.GetType();");

            bool first = true;

            if (member.Boxed == BoxedDeclaration.Array)
            {
                // The member element declares nothing, so each item binds the Arrays namespace as a
                // default xmlns of its own. That is the visible difference from a typed collection,
                // where the namespace is declared once on the member and the items carry a prefix.
                _builder.AppendLine($"{indentor}if (__runtimeType == typeof(object[]))");
                _builder.AppendLine($"{indentor}{{");
                indentor.Increment();
                _builder.AppendLine($"{indentor}foreach (object __item in (object[]){value})");
                _builder.AppendLine($"{indentor}{{");
                indentor.Increment();
                _builder.AppendLine($"{indentor}writer.WriteStartElement(\"anyType\", {Literal(CollectionNamespace)});");
                _builder.AppendLine($"{indentor}WriteAnyType(writer, __item);");
                _builder.AppendLine($"{indentor}writer.WriteEndElement();");
                indentor.Decrement();
                _builder.AppendLine($"{indentor}}}");
                indentor.Decrement();
                _builder.AppendLine($"{indentor}}}");
                first = false;
            }

            if (member.Boxed == BoxedDeclaration.Object)
            {
                _builder.AppendLine($"{indentor}if (__runtimeType == typeof(object))");
                _builder.AppendLine($"{indentor}{{");
                indentor.Increment();
                _builder.AppendLine($"{indentor}// anyType: neither i:type nor content");
                indentor.Decrement();
                _builder.AppendLine($"{indentor}}}");
                first = false;
            }

            foreach ((string clrType, MemberKind kind, string xsiName, string xsiNamespace, bool isValueType) in BoxedPrimitives)
            {
                // A member declared as ValueType cannot hold a string, and casting one to string is
                // a compile error rather than a branch that never runs - so the table is filtered
                // rather than emitted whole. An Enum member admits no primitive at all.
                if (member.Boxed is BoxedDeclaration.Enum or BoxedDeclaration.Array
                    || (member.Boxed == BoxedDeclaration.ValueType && !isValueType))
                {
                    continue;
                }

                _builder.AppendLine($"{indentor}{(first ? "if" : "else if")} (__runtimeType == typeof({clrType}))");
                first = false;
                _builder.AppendLine($"{indentor}{{");
                indentor.Increment();
                EmitXsiType(indentor, xsiName, xsiNamespace);
                _builder.AppendLine($"{indentor}{WriteValueStatement(kind, $"(({clrType}){value})")}");
                indentor.Decrement();
                _builder.AppendLine($"{indentor}}}");
            }

            foreach (string candidate in member.Candidates)
            {
                ContractSpec spec = _contractSpecs[candidate];

                _builder.AppendLine($"{indentor}{(first ? "if" : "else if")} (__runtimeType == typeof({candidate}))");
                first = false;
                _builder.AppendLine($"{indentor}{{");
                indentor.Increment();
                EmitXsiType(indentor, spec.ContractName, spec.ContractNamespace);

                string typed = $"(({candidate}){value})";

                if (spec.IsReference)
                {
                    _builder.AppendLine($"{indentor}if (!scope.WriteIdOrRef(writer, {value}))");
                    _builder.AppendLine($"{indentor}{{");
                    indentor.Increment();
                    _builder.AppendLine($"{indentor}{ContentWriterName(candidate)}(writer, {typed}, scope);");
                    indentor.Decrement();
                    _builder.AppendLine($"{indentor}}}");
                }
                else
                {
                    EmitByValueContentCall(indentor, candidate, value, typed);
                }

                indentor.Decrement();
                _builder.AppendLine($"{indentor}}}");
            }

            foreach (string enumCandidate in member.EnumCandidates)
            {
                EnumSpec spec = _enumSpecs[enumCandidate];

                _builder.AppendLine($"{indentor}{(first ? "if" : "else if")} (__runtimeType == typeof({enumCandidate}))");
                first = false;
                _builder.AppendLine($"{indentor}{{");
                indentor.Increment();
                EmitXsiType(indentor, spec.ContractName, spec.ContractNamespace);
                EmitWriteEnum(indentor, enumCandidate, $"(({enumCandidate}){value})");
                indentor.Decrement();
                _builder.AppendLine($"{indentor}}}");
            }

            _builder.AppendLine($"{indentor}{(first ? "if (true)" : "else")}");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            _builder.AppendLine($"{indentor}throw new global::System.Runtime.Serialization.SerializationException(");
            indentor.Increment();
            _builder.AppendLine($"{indentor}\"Type '\" + __runtimeType.FullName + \"' cannot be written into an object member by this contract.\");");
            indentor.Decrement();
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
        }

        /// <summary>
        /// The CLR type, writer and xsi type name of every primitive a boxed value may be.
        /// </summary>
        /// <remarks>
        /// Recorded from the SanityBoxedPrimitives fixture. Two things it settles that guesswork
        /// gets wrong: sbyte is "byte" while byte is "unsignedByte", and char, Guid and TimeSpan are
        /// named in the serialization namespace because XML Schema has nothing to call them.
        /// </remarks>
        private static IEnumerable<(string ClrType, MemberKind Kind, string XsiName, string XsiNamespace, bool IsValueType)> BoxedPrimitives
        {
            get
            {
                yield return ("bool", MemberKind.Boolean, "boolean", SchemaNamespace, true);
                yield return ("byte[]", MemberKind.ByteArray, "base64Binary", SchemaNamespace, false);
                yield return ("char", MemberKind.Char, "char", SerializationNamespace, true);
                yield return ("global::System.DateTime", MemberKind.DateTime, "dateTime", SchemaNamespace, true);
                yield return ("decimal", MemberKind.Decimal, "decimal", SchemaNamespace, true);
                yield return ("double", MemberKind.Double, "double", SchemaNamespace, true);
                yield return ("float", MemberKind.Single, "float", SchemaNamespace, true);
                yield return ("global::System.Guid", MemberKind.Guid, "guid", SerializationNamespace, true);
                yield return ("short", MemberKind.Int16, "short", SchemaNamespace, true);
                yield return ("int", MemberKind.Int32, "int", SchemaNamespace, true);
                yield return ("long", MemberKind.Int64, "long", SchemaNamespace, true);
                yield return ("sbyte", MemberKind.SByte, "byte", SchemaNamespace, true);
                yield return ("string", MemberKind.String, "string", SchemaNamespace, false);
                yield return ("global::System.TimeSpan", MemberKind.TimeSpan, "duration", SerializationNamespace, true);
                yield return ("global::System.Uri", MemberKind.Uri, "anyURI", SchemaNamespace, false);
                yield return ("ushort", MemberKind.UInt16, "unsignedShort", SchemaNamespace, true);
                yield return ("uint", MemberKind.UInt32, "unsignedInt", SchemaNamespace, true);
                yield return ("ulong", MemberKind.UInt64, "unsignedLong", SchemaNamespace, true);
                yield return ("byte", MemberKind.Byte, "unsignedByte", SchemaNamespace, true);
            }
        }

        /// <summary>
        /// Emits the <c>i:type</c> attribute naming a contract.
        /// </summary>
        /// <remarks>
        /// Mirrors XmlWriterDelegator.WriteAttributeQualifiedName: the value's namespace is declared
        /// first, then the attribute is opened and the qualified name written into it. Declaring
        /// first is what lets the writer reuse a prefix already in scope - which is why i:type on a
        /// contract in the root's own namespace reads "a:Derived" and adds no declaration, while one
        /// in a different namespace brings its own xmlns with it.
        /// </remarks>
        private void EmitXsiType(Indentor indentor, ContractSpec contract) =>
            EmitXsiType(indentor, contract.ContractName, contract.ContractNamespace);

        private void EmitXsiType(Indentor indentor, string name, string ns)
        {
            _builder.AppendLine($"{indentor}writer.WriteXmlnsAttribute(null, {Literal(ns)});");
            _builder.AppendLine($"{indentor}writer.WriteStartAttribute(\"i\", \"type\", {Literal(SchemaInstanceNamespace)});");
            _builder.AppendLine($"{indentor}writer.WriteQualifiedName({Literal(name)}, {Literal(ns)});");
            _builder.AppendLine($"{indentor}writer.WriteEndAttribute();");
        }

        /// <summary>
        /// The statement that writes a member's value.
        /// </summary>
        /// <remarks>
        /// Every case here matches XmlWriterDelegator in dotnet/runtime. The non-obvious ones:
        /// char is written as its numeric value, not as a character; Guid, TimeSpan and ulong go
        /// through WriteRaw because XmlWriter has no WriteValue overload for them; byte[] is base64.
        /// ulong is the one that bites quietly - WriteValue(ulong) is not missing so much as
        /// ambiguous, since ulong converts implicitly to float, double and decimal and to none of
        /// them better than the others, so the mistake surfaces as CS0121 in generated code rather
        /// than as wrong output.
        /// </remarks>
        private static string WriteValueStatement(MemberKind kind, string value) => kind switch
        {
            MemberKind.Char => $"writer.WriteValue((int){value});",
            MemberKind.Guid => $"writer.WriteRaw({value}.ToString());",
            MemberKind.TimeSpan => $"writer.WriteRaw({XmlConvert}.ToString({value}));",
            MemberKind.UInt64 => $"writer.WriteRaw({XmlConvert}.ToString({value}));",
            MemberKind.ByteArray => $"writer.WriteBase64({value}, 0, {value}.Length);",

            // Not ToString(): SerializationInfoString is the round-trippable form, and it is what
            // adds the trailing slash the fixtures record for an authority-only Uri.
            MemberKind.Uri =>
                $"writer.WriteString({value}.GetComponents(global::System.UriComponents.SerializationInfoString, global::System.UriFormat.UriEscaped));",

            MemberKind.DateTimeOffset => $"WriteDateTimeOffset(writer, {value});",
            MemberKind.QName => $"WriteQName(writer, {value});",
            MemberKind.DateOnly => $"WriteDateOnly(writer, {value});",
            MemberKind.TimeOnly => $"WriteTimeOnly(writer, {value});",
            _ => $"writer.WriteValue({value});"
        };

        /// <summary>
        /// The test for "this member is at its type's default", as
        /// <c>EmitDefaultValue = false</c> defines it.
        /// </summary>
        private static string IsDefaultExpression(MemberSpec member, string access)
        {
            if (member.IsNullableValueType)
            {
                return $"!{access}.HasValue";
            }

            return member.Kind switch
            {
                MemberKind.String or MemberKind.ByteArray or MemberKind.Contract or MemberKind.Collection or MemberKind.Dictionary
                    or MemberKind.Object or MemberKind.Uri or MemberKind.QName => $"{access} == null",
                MemberKind.Boolean => $"!{access}",
                _ => $"{access} == default"
            };
        }

        /// <summary>
        /// Emits the shared enum writer: one copy of the algorithm, driven by a per-enum table.
        /// </summary>
        /// <remarks>
        /// Mirrors EnumDataContract.WriteEnumValue. An exact value match wins even for a flags enum,
        /// which is why the combined value is looked up before any decomposition. A flags value that
        /// cannot be fully decomposed is an error rather than a partial write, and a zero that
        /// matched nothing falls back to the member declared as zero, if there is one.
        /// </remarks>
        private void EmitEnumHelper(Indentor indentor)
        {
            _builder.AppendLine();
            _builder.AppendLine($"{indentor}private static void WriteEnum({DictionaryWriter} writer, long longValue, long[] values, string[] names, bool isFlags, string typeName)");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            _builder.AppendLine($"{indentor}for (int i = 0; i < values.Length; i++)");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            _builder.AppendLine($"{indentor}if (longValue == values[i])");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            _builder.AppendLine($"{indentor}writer.WriteString(names[i]);");
            _builder.AppendLine($"{indentor}return;");
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
            indentor.Decrement();
            _builder.AppendLine($"{indentor}}}");
            _builder.AppendLine();
            _builder.AppendLine($"{indentor}if (isFlags)");
            _builder.AppendLine($"{indentor}{{");
            indentor.Increment();
            _builder.AppendLine($"{indentor}int zeroIndex = -1;");
            _builder.AppendLine($"{indentor}bool noneWritten = true;");
